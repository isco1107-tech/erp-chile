const { chromium } = require('playwright');
const { readFileSync } = require('node:fs');
const { randomUUID } = require('node:crypto');
const assert = require('node:assert/strict');
(async () => {
  const origin = process.env.WAREHOUSE_TEST_ORIGIN || 'http://localhost:3101';
  const seed = JSON.parse(readFileSync('.codex-audit/warehouse/browser-session.json', 'utf8'));
    const identity = JSON.parse(Buffer.from(seed.token.split('.')[1], 'base64url').toString('utf8'));
    const expectedScope = `${seed.companyId}:${seed.userId ?? identity.id}`;
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, serviceWorkers: 'allow' });
    await context.addCookies([{ name: 'session', value: seed.token, domain: 'localhost', path: '/', httpOnly: true, sameSite: 'Strict', secure: false }]);
    const page = await context.newPage();
    const errors = [];
    const failed = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('requestfailed', (request) => failed.push({ url: request.url(), error: request.failure()?.errorText }));
    const anon = await browser.newContext();
    assert.equal((await anon.request.get(`${origin}/api/warehouse/bootstrap`)).status(), 401);
    await anon.close();
    assert.equal((await context.request.post(`${origin}/api/warehouse/sync`, { headers: { Origin: 'https://otro.example' }, data: { operations: [] } })).status(), 403);
    const navigation = await page.goto(`${origin}/bodega`, { waitUntil: 'domcontentloaded', timeout: 120000 });
    assert.match(navigation.headers()['permissions-policy'], /camera=\(self\)/);
    await page.getByRole('heading', { name: '¿Qué vas a hacer?' }).waitFor({ timeout: 120000 });
    await page.screenshot({ path: '.codex-audit/warehouse/mobile-home.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.getByRole('button', { name: /Sacar Registrar/ }).click();
    await page.getByRole('button', { name: /Producto de prueba/ }).click();
    await page.getByLabel('Lote físico').fill('A');
    await page.getByRole('textbox', { name: 'Cantidad', exact: true }).fill('1');
    await page.getByRole('button', { name: 'Confirmar y seguir' }).click();
    await page.getByText('Guardado en este teléfono. Puedes seguir con el próximo producto.').waitFor();
    await page.getByRole('button', { name: 'Registros', exact: true }).click();
    await page.getByText('Confirmado en Aether', { exact: true }).first().waitFor({ timeout: 60000 });
    await page.getByRole('button', { name: 'Registros', exact: true }).click();
    await page.getByRole('button', { name: 'Preparar lectura sin señal' }).click();
    await page.getByRole('button', { name: 'Lectura preparada', exact: true }).waitFor({ timeout: 180000 });
    await context.setOffline(true);
    await page.reload({ waitUntil: 'domcontentloaded', timeout: 30000 });
    await page.getByRole('heading', { name: '¿Qué vas a hacer?' }).waitFor({ timeout: 30000 });
    await page.getByRole('button', { name: /Sacar Registrar/ }).click();
    await page.getByRole('button', { name: /Producto de prueba/ }).click();
    const label = await page.evaluate(() => {
      const canvas = document.createElement('canvas');
      canvas.width = 1200; canvas.height = 360;
      const drawing = canvas.getContext('2d');
      drawing.fillStyle = 'white'; drawing.fillRect(0, 0, 1200, 360);
      drawing.fillStyle = 'black'; drawing.font = '72px Arial';
      drawing.fillText('LOTE: A', 70, 130);
      drawing.fillText('VENC: 01/01/2027', 70, 260);
      return canvas.toDataURL('image/png').split(',')[1];
    });
    await page.locator('input[type=file]').setInputFiles({ name: 'etiqueta.png', mimeType: 'image/png', buffer: Buffer.from(label, 'base64') });
    await page.waitForFunction(() => document.querySelector('#warehouse-lot')?.value === 'A', null, { timeout: 60000 });
    await page.getByRole('button', { name: 'Foto etiqueta' }).waitFor({ timeout: 60000 });
    await page.getByRole('textbox', { name: 'Cantidad', exact: true }).fill('1');
    await page.getByRole('button', { name: 'Confirmar y seguir' }).click();
    await page.getByText('Guardado en este teléfono. Puedes seguir con el próximo producto.').waitFor();
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByRole('heading', { name: '¿Qué vas a hacer?' }).waitFor();
    await page.getByRole('button', { name: 'Registros', exact: true }).click();
    await page.getByText('En este teléfono', { exact: true }).waitFor();
    await page.screenshot({ path: '.codex-audit/warehouse/mobile-offline.png', fullPage: true });
    await context.setOffline(false);
    await page.getByRole('button', { name: 'Sincronizar y actualizar existencias' }).click();
    await page.getByText('En este teléfono', { exact: true }).waitFor({ state: 'hidden', timeout: 60000 });
    // La misma intención se reenvía sin duplicar, comprobando el endpoint real.
    const op = { protocol: 1, id: randomUUID(), deviceId: randomUUID(), capturedAt: new Date().toISOString(), kind: 'OUT', productId: seed.productId, warehouseId: seed.warehouseId, lotNumber: 'A', quantity: 1, note: 'Prueba E2E idempotente' };
    const first = await context.request.post(`${origin}/api/warehouse/sync`, { headers: { Origin: origin }, data: { expectedScope, operations: [op] } });
    const second = await context.request.post(`${origin}/api/warehouse/sync`, { headers: { Origin: origin }, data: { expectedScope, operations: [op] } });
    assert.equal(first.status(), 200); assert.equal(second.status(), 200); assert.deepEqual(await first.json(), await second.json());
    await page.screenshot({ path: '.codex-audit/warehouse/mobile-synced.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ browser: 'passed', offlineReload: true, offlineOcr: true, durableQueue: true, reconnected: true, idempotency: true, csrf: true, unauthenticated: true, horizontalOverflow: false, consoleErrors: errors, failedRequests: failed.length }));
    await context.close();
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
